#!/usr/bin/env python3
"""spice_input.py — generate a SPICE netlist skeleton for the power rail.

Writes a .spice deck skeleton: input source, buck converter as an
ideal voltage source with series resistance, decoupling capacitors.
Component values are UNVERIFIED placeholders unless the spec states
measured values. It does NOT run the simulation. Status:
  * READY — ngspice found on PATH (run it manually)
  * NOT_RUN — ngspice not installed

Standard library only.
"""
import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
from common import load_spec


def main():
    ap = argparse.ArgumentParser(description="Generate a SPICE power-rail netlist skeleton.")
    ap.add_argument("spec", help="Camera spec JSON")
    ap.add_argument("outdir", help="Directory to write the .spice file into")
    args = ap.parse_args()

    spec, err = load_spec(args.spec)
    if err:
        print(f"ERROR: {err}")
        return 2
    cam = spec.get("camera", {})
    power = cam.get("power", {})
    input_v = power.get("input_v", 5)
    peak_w = power.get("peak_w", 5.0)
    load_a = peak_w / input_v if input_v else 1.0

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    deck = outdir / "power_rail.spice"
    deck.write_text(
        f"""* Generated by ai-camera-vision-pcbs-design-skill-addon (v0.0.1).
* SPICE netlist skeleton for the camera power rail — INPUT ONLY.
* Values are UNVERIFIED placeholders: take the regulator, inductor
* and capacitor values from their datasheets before trusting a result.
* Input: {input_v} V, peak load {peak_w} W (~{load_a:.2f} A).
V1 VIN 0 DC {input_v}
* Ideal buck model: replace with the real regulator subcircuit.
E1 VOUT 0 VIN 0 0.66
Rser VOUT VLOAD 0.05
* Decoupling: replace with the real BOM values.
C1 VLOAD 0 10u
C2 VLOAD 0 100n
Rload VLOAD 0 {input_v / load_a:.2f}
.tran 0 10m 0 10u
.end
""",
        encoding="utf-8",
    )
    print(f"Wrote {deck}")
    if shutil.which("ngspice"):
        print("READY — ngspice found; run it manually: ngspice power_rail.spice")
        print("Do NOT treat the generated file as a result — read the simulator output.")
        return 0
    print("NOT_RUN — ngspice not installed; no simulation was run, no result exists.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""thermal_input.py — generate an Elmer FEM heat-equation input (.sif).

Reads a camera spec and writes a minimal Elmer FEM case: the sensor
and processor as heat sources inside an enclosure, ambient
temperature from the spec. It does NOT run the simulation and does
NOT claim any result. Status:
  * READY — ElmerSolver found on PATH (run it manually)
  * NOT_RUN — ElmerSolver not installed

Standard library only.
"""
import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
from common import load_spec


def main():
    ap = argparse.ArgumentParser(description="Generate Elmer FEM thermal input.")
    ap.add_argument("spec", help="Camera spec JSON")
    ap.add_argument("outdir", help="Directory to write the .sif file into")
    args = ap.parse_args()

    spec, err = load_spec(args.spec)
    if err:
        print(f"ERROR: {err}")
        return 2
    cam = spec.get("camera", {})
    thermal = cam.get("thermal", {})
    power = cam.get("power", {})
    ambient = thermal.get("ambient_max_c", 25)
    peak_w = power.get("peak_w", 5.0)
    max_c = thermal.get("max_component_c", 70)

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    sif = outdir / "thermal.sif"
    sif.write_text(
        f"""! Generated by ai-camera-vision-pcbs-design-skill-addon (v0.0.1).
! Elmer FEM heat-equation case — INPUT ONLY, not a result.
! Material values below are UNVERIFIED placeholders: take thermal
! conductivity from the enclosure / PCB material datasheet.
Header
  Mesh DB "." "mesh"
End
Simulation
  Max Output Level = 5
  Coordinate System = Cartesian
  Simulation Type = Steady state
  Steady State Max Iterations = 50
End
Constants
  AmbientTemperature = {ambient}  ! deg C, from spec thermal.ambient_max_c
  PeakPower = {peak_w}  ! W, from spec power.peak_w
  MaxComponentTemp = {max_c}  ! deg C, from spec thermal.max_component_c
End
Body 1
  Name = "Enclosure"
  Equation = 1
  Material = 1
  Initial Condition = 1
End
Material 1
  Name = "Enclosure (UNVERIFIED)"
  Heat Conductivity = 0.2  ! UNVERIFIED placeholder (plastic) — replace from datasheet
  Heat Capacity = 1000.0  ! UNVERIFIED placeholder
  Density = 1200.0  ! UNVERIFIED placeholder
End
Equation 1
  Name = "Heat Equation"
  Active Solvers(1) = 1
End
Solver 1
  Equation = Heat Equation
  Procedure = "HeatSolve" "HeatSolver"
  Variable = Temperature
  Exec Solver = Always
  Stabilize = True
  Linear System Solver = Iterative
  Linear System Iterative Method = BiCGStab
  Linear System Max Iterations = 500
  Linear System Convergence Tolerance = 1.0e-8
End
Boundary Condition 1
  Name = "Outer surface (convection to ambient)"
  Target Boundaries(1) = 1
  Heat Flux BC = True
  External Temperature = $AmbientTemperature
  Heat Transfer Coefficient = 10.0  ! UNVERIFIED placeholder — measure or estimate
End
""",
        encoding="utf-8",
    )
    print(f"Wrote {sif}")
    if shutil.which("ElmerSolver"):
        print("READY — ElmerSolver found; run it manually: ElmerSolver thermal.sif")
        print("Do NOT treat the generated file as a result — read the solver output.")
        return 0
    print("NOT_RUN — ElmerSolver not installed; no simulation was run, no result exists.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

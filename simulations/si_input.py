#!/usr/bin/env python3
"""si_input.py — generate an openEMS input for one MIPI CSI-2 diff pair.

Writes an openEMS XML case for a single differential pair with the
lane rate from the spec and an 85 ohm differential target. It does
NOT run the simulation and does NOT claim any result. Status:
  * READY — openEMS found on PATH (run it manually)
  * NOT_RUN — openEMS not installed

Standard library only.
"""
import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))
from common import load_spec


def main():
    ap = argparse.ArgumentParser(description="Generate openEMS signal-integrity input.")
    ap.add_argument("spec", help="Camera spec JSON")
    ap.add_argument("outdir", help="Directory to write the XML file into")
    args = ap.parse_args()

    spec, err = load_spec(args.spec)
    if err:
        print(f"ERROR: {err}")
        return 2
    cam = spec.get("camera", {})
    iface = cam.get("interface", {})
    lane_rate = iface.get("lane_rate_gbps", 1.5)
    lanes = iface.get("lanes", 2)

    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    xml = outdir / "mipi_pair.xml"
    xml.write_text(
        f"""<!-- Generated by ai-camera-vision-pcbs-design-skill-addon (v0.0.1). -->
<!-- openEMS input — INPUT ONLY, not a result. -->
<!-- Geometry values are UNVERIFIED placeholders: take trace width, -->
<!-- spacing and stackup from the real board (base skill §7) and the -->
<!-- fab's impedance calculator before trusting any result. -->
<openEMS>
  <name>MIPI CSI-2 differential pair</name>
  <lane_rate_gbps>{lane_rate}</lane_rate_gbps>
  <lanes>{lanes}</lanes>
  <target_diff_impedance_ohm>85</target_diff_impedance_ohm>
  <!-- UNVERIFIED placeholder geometry — replace with the real layout -->
  <trace width_mm="0.12" spacing_mm="0.12" length_mm="50.0"/>
  <substrate er="4.4" note="UNVERIFIED placeholder (FR-4 nominal)"/>
  <excitation type="differential" rise_time_ps="100"/>
</openEMS>
""",
        encoding="utf-8",
    )
    print(f"Wrote {xml}")
    if shutil.which("openEMS"):
        print("READY — openEMS found; run it manually on mipi_pair.xml")
        print("Do NOT treat the generated file as a result — read the solver output.")
        return 0
    print("NOT_RUN — openEMS not installed; no simulation was run, no result exists.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
